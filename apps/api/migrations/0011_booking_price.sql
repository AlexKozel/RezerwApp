-- Снимок цены визита на момент бронирования (D-056): выручка и маржа за прошлые периоды не меняются
-- при смене цен. Для записей до этой миграции цена NULL, аналитика берёт текущую цену варианта.
-- Заполнять старые строки здесь бессмысленно: в проде миграцию выполняет владелец схемы, а при FORCE RLS
-- без контекста Account UPDATE затронул бы 0 строк.
ALTER TABLE bookings ADD COLUMN price numeric(10, 2) CHECK (price IS NULL OR price >= 0);
